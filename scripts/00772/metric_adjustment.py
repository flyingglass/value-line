def adjust_metrics(reader, rd, np_val, tax_rate, stock_cfg):
    """保持 IFRS 归母净利；亏损年度附注说明口径。"""
    if np_val is None:
        return np_val, []
    footnote = (f"IFRS口径归母净利 {np_val / 1e8:.1f}亿 (未剔除商誉减值等非经常项目); "
                f"公司non-IFRS口径见年度报告调节表")
    return np_val, [footnote]
