"""川仪股份 603100 — 每股分红(DPS)口径调整。

问题: DB dividend 表由 AKShare 分红送配接口写入, 只含 **年度** 分配方案, 缺失中期/三季度分红;
      且 2024 年公司实施资本公积转增股本 (每10股转增3股, 股本 3.95亿 → 5.13亿股),
      转增前年度的每股分红与现行股本口径不可比。

原始依据 (2025年报 P59-60「八、利润分配或资本公积金转增预案」原文):
  - 2024年度: 三季度已分配 0.30元/股 (154,010,025.00元) + 年度 0.275元/股 (141,130,408.10元)
             合计 295,140,433.10元, 占2024年归母净利(778,051,518.24元)的 37.93%
  - 2025年度: 三季度已分配 0.30元/股 (153,951,952.80元) + 年度 0.21元/股 (107,766,366.96元)
             合计 261,718,319.76元, 占2025年归母净利(642,546,680.53元)的 40.73%
             (含回购注销 1,288,634.63元后为 40.93%)
  - 最近三个会计年度累计现金分红 853,031,877.86元 = 2023年度2.96亿 + 2024年度2.95亿 + 2025年度2.62亿

口径处理:
  - 2024/2025: 三季度 + 年度, 直接相加 (均在 5.13 亿股口径下派发)
  - 2014-2023: 原方案按转增前股本(3.95亿股)派发, 统一 ÷1.3 折算为现行股本口径,
              与 THS 已追溯调整的 EPS(2023=1.46元, 即原1.88÷1.3)保持同一每股基准
  - 2009-2013: 股本 2.95 亿股 (2014年上市增发至3.95亿股), 按 ÷(5.13/2.95) 折算

数据来源: 年报PDF原文(2014-2025各年度利润分配章节) + DB dividend 表, 见注释内逐年出处。
"""
import sqlite3, os

# 年度现金分红总额 (元) — 年报原文披露值优先
_TOTAL_DIV = {
    2014: 47340000.0,    # 0.12元/股 × 3.95亿股 (2014年报利润分配)
    2015: 47340000.0,    # 0.12元/股 × 3.95亿股
    2016: 39500000.0,    # 0.10元/股 × 3.95亿股
    2017: 51350000.0,    # 0.13元/股 × 3.95亿股
    2018: 79000000.0,    # 0.20元/股 × 3.95亿股
    2019: 79000000.0,    # 0.20元/股 × 3.95亿股
    2020: 118500000.0,   # 0.30元/股 × 3.95亿股
    2021: 237000000.0,   # 0.60元/股 × 3.95亿股
    2022: 236970000.0,   # 0.60元/股 × 3.95亿股 (2024年报 P134 利润分配 -236,970,000 元)
    2023: 296173125.0,   # 三年累计 853,031,877.86 - 2024年 295,140,433.10 - 2025年 261,718,319.76
    2024: 295140433.10,  # 2025年报 P59: 三季度 154,010,025.00 + 年度 141,130,408.10
    2025: 261718319.76,  # 2025年报 P60: 三季度 153,951,952.80 + 年度 107,766,366.96
}

# 各年度派息时的股本 (股)
_SHARES_THEN = {
    2014: 395000000, 2015: 395000000, 2016: 395000000, 2017: 395000000,
    2018: 395000000, 2019: 395000000, 2020: 395000000, 2021: 395000000,
    2022: 395000000, 2023: 394995000, 2024: 513201484, 2025: 513173176,
}
_CUR_SHARES = 513173176  # 现行总股本


def adjust_dividends(reader, stock_cfg):
    """返回 {year: 每股分红(元, 统一按现行 5.13 亿股摊薄)}

    注意: engine 的 years 为字符串('2025'), 键必须用 str, 否则 row["DPS"] 取不到值。
    """
    return {str(yr): round(total / _CUR_SHARES, 4) for yr, total in _TOTAL_DIV.items()}


if __name__ == "__main__":
    conn = sqlite3.connect(os.path.join(
        os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))), "data/603100.db"))
    db_dps = {r[0]: r[1] for r in conn.execute("SELECT report_year, cash_dps FROM dividend")}
    adj = adjust_dividends(None, {})
    print(f"{'年度':<6}{'DB每股':>10}{'调整后每股':>12}{'分红总额(亿)':>14}")
    for yr in sorted(adj):
        print(f"{yr:<6}{db_dps.get(str(yr), 0):>10.3f}{adj[yr]:>12.4f}{_TOTAL_DIV[yr]/1e8:>14.2f}")
    conn.close()
