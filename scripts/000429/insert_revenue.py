# -*- coding: utf-8 -*-
"""粤高速A(000429) 营收结构数据 — 从年报PDF原文逐字提取

来源:
  2025年报 P149-150 附注35「营业收入、营业成本的分解信息」
  2025年报 P11-13   「主营业务分析 / 收入与成本 / (1) 营业收入构成」
  2024年报 P162-163 附注35「营业收入、营业成本的分解信息」(交叉验证)
  2024年报 P12      「(1) 营业收入构成」(交叉验证)

金额单位: 源数据为元, 入库统一换算为百万元 (÷1e6, 与全库 revenue_structure.amount 约定一致,
          engine 交叉校验按 1e6 元换算)
百分比: 分项金额 / 当年营业收入合计  (两年均严格加总 = 100.00%)

营业收入合计:
  - 2025 4,469,738,160.51 元 (= 44.6974 百万元×100)
  - 2024 4,569,903,078.72 元

口径说明 (重要):
1. by_product 采用 **年报附注35 业务类型口径** (通行费收入/服务及其他收入/租赁收入, 三值),
   而非年报主表「分产品」口径 (公路运输/其他, 两值)。
   理由: 主表分产品/分行业/分销售模式三维取值完全相同 (公路运输 98%+其他 2%),
   信息量低; 附注业务类型口径更细且加总同样等于营业收入合计。
   对应关系: 主表「其他」87,122,537.78 元 = 服务及其他收入 46,031,614.55 + 租赁收入 41,090,923.23 (2025);
             主表「其他」70,077,811.29 元 = 服务及其他收入 41,638,860.55 + 租赁收入 28,438,950.74 (2024)。已核对相符。
2. by_region 采用年报「营业收入构成 - 分地区」口径, 实为 **控股并表路段** 拆分。
   广佛高速 2022-03-03 起停止收费 (粤交营便函【2022】24号文), 收入为 0, 不入库。
   惠盐/广肇/江中/康大/赣康/广乐高速均为 **参股** 路段, 其通行费收入不计入营业收入
   (体现在投资收益), 故不出现在本表 —— 引用时必须区分「控股路段」与「参股路段」。
3. 分路段通行费收入 (2025年报 P11-12, 万元) 与 by_region 的关系:
   佛开 142,377.62 + 京珠广珠段 95,553.75 + 广惠 200,330.19 = 438,261.56 万元
   ≈ 通行费收入 4,382,615,622.73 元 (438,261.56 万元), 已核对相符。
4. 两年口径一致, 2025年报未对 2024 年比较数据做重述 (2024年报原文与2025年报比较列逐项相符)。
"""
import sqlite3, os

_root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
conn = sqlite3.connect(os.path.join(_root, "data/000429.db"))

_RAW = [  # (code, year, dim_type, dim_name, 金额元, pct)
    # ========== by_product (业务类型, 来源: 年报附注35 营业收入分解) ==========
    # 2025 (来源: 2025年报 P149-150)
    ("000429", "2025", "by_product", "通行费收入",       4382615622.73, 98.05),
    ("000429", "2025", "by_product", "服务及其他收入",     46031614.55,  1.03),
    ("000429", "2025", "by_product", "租赁收入",           41090923.23,  0.92),
    # 2024 (来源: 2024年报 P163, 与2025年报「上期金额」列一致)
    ("000429", "2024", "by_product", "通行费收入",       4499825267.43, 98.47),
    ("000429", "2024", "by_product", "服务及其他收入",     41638860.55,  0.91),
    ("000429", "2024", "by_product", "租赁收入",           28438950.74,  0.62),
    # ========== by_region (控股并表路段, 来源: 年报「营业收入构成-分地区」) ==========
    # 2025 (来源: 2025年报 P12-13)
    ("000429", "2025", "by_region", "广惠高速公路",      2003301935.02, 44.82),
    ("000429", "2025", "by_region", "佛开高速公路",      1423776151.84, 31.85),
    ("000429", "2025", "by_region", "京珠高速广珠段",     955537535.87, 21.38),
    ("000429", "2025", "by_region", "其他",               87122537.78,  1.95),
    # 2024 (来源: 2024年报 P12, 与2025年报比较列一致)
    ("000429", "2024", "by_region", "广惠高速公路",      1924805181.43, 42.12),
    ("000429", "2024", "by_region", "佛开高速公路",      1495267944.19, 32.72),
    ("000429", "2024", "by_region", "京珠高速广珠段",    1079757126.95, 23.63),
    ("000429", "2024", "by_region", "其他",               70077811.29,  1.53),
]

# 单位换算: 元 → 百万元
data = [(c, y, d, n, round(amt / 1e6, 2), p) for (c, y, d, n, amt, p) in _RAW]

conn.executemany(
    "INSERT OR REPLACE INTO revenue_structure (code, year, dim_type, dim_name, amount, pct) VALUES (?,?,?,?,?,?)",
    data,
)
conn.commit()

# 自洽检验: 各维度分项加总应 = 当年营业收入合计
print("自洽检验 (分项加总 vs 营业收入合计):")
_TOTAL = {"2025": 4469.74, "2024": 4569.90}   # 百万元 (年报口径 4,469,738,160.51 / 4,569,903,078.72)
for yr in ("2024", "2025"):
    for dim in ("by_product", "by_region"):
        n, amt_sum, pct_sum = conn.execute(
            "SELECT COUNT(*), ROUND(SUM(amount),2), ROUND(SUM(pct),2) FROM revenue_structure "
            "WHERE code='000429' AND year=? AND dim_type=?", (yr, dim)).fetchone()
        diff = round(amt_sum - _TOTAL[yr], 2)
        print(f"  {yr} {dim}: {n} rows, amount_sum={amt_sum} 百万元 "
              f"(合计{_TOTAL[yr]}, 差{diff:+.2f}), pct_sum={pct_sum}%")

total = conn.execute("SELECT COUNT(*) FROM revenue_structure WHERE code='000429'").fetchone()[0]
print(f"\n  总计: {total} 条记录")
conn.close()
print("Done.")
