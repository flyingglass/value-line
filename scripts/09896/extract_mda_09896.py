def main():
    conn = sqlite3.connect(config.db_path(CODE))
    conn.execute("CREATE TABLE IF NOT EXISTS meta (key TEXT PRIMARY KEY, value TEXT)")
    for k, v in [
        ("mda_text", MDA.strip()),
        ("mda_quality", "1"),
        ("mda_extracted_year", "2025"),
        ("mda_source", "09896_名创优品_2025_年报.pdf P15-17/P24-27/附注4-5（结构化摘录，人工核对）"),
    ]:
        conn.execute("INSERT OR REPLACE INTO meta VALUES (?,?)", (k, v))
    conn.commit()
    conn.close()
    print(f"  mda_text 写入 {len(MDA)} 字符（6 个板块）")


if __name__ == "__main__":
    main()
